import pytest
from app.text_preprocessor import RussianTextPreprocessor


@pytest.mark.parametrize('text,expected', [
    ('В России информация о компании и интеграции.', 'В России информация о компании и интеграции.'),
    ('ИИ-консультант МастерЧеб', 'виртуальный консультант Мастер Чеб'),
    ('поручить ИИ-помощнику', 'поручить виртуальному помощнику'),
    ('разбираться в ИИ', 'разбираться в искусственном интеллекте'),
    ('от 50 000 рублей', 'от пятидесяти тысяч рублей'),
    ('от 250 000 ₽', 'от двухсот пятидесяти тысяч рублей'),
    ('1–3 недели', 'от одной до трёх недель'),
    ('демонстрация на 1–3 дня', 'демонстрация на срок от одного до трёх дней'),
    ('по почте test@example.com', 'по электронной почте, указанной в чате'),
])
def test_pronunciation_regressions(text, expected):
    assert RussianTextPreprocessor().preprocess(text) == expected
